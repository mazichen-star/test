-- ===== PAA-DA 黏附：文献数据 =====
create table if not exists public.adhesion_literature (
    id bigint generated by default as identity primary key,
    username text not null,
    source_file text not null default '',
    title text not null default '',
    doi text not null default '',
    page integer,
    quote text not null default '',
    material_system text not null default 'PAA-DA',
    dopamine_content double precision,
    polymer_concentration double precision,
    ph double precision,
    curing_temp_c double precision,
    curing_time_min double precision,
    crosslinker text not null default '',
    substrate text not null default '',
    test_type text not null default 'unknown',
    adhesion_value double precision,
    adhesion_unit text not null default '',
    adhesion_target double precision,
    target_unit text not null default '',
    test_temp_c double precision,
    humidity double precision,
    confidence double precision,
    created_at timestamptz not null default now()
);

create index if not exists idx_adhesion_lit_user
    on public.adhesion_literature (username, id desc);

-- ===== PAA-DA 黏附：标准化实验数据 =====
create table if not exists public.adhesion_experiments (
    id bigint generated by default as identity primary key,
    username text not null,
    sample_id text not null default '',
    dopamine_content double precision,
    polymer_concentration double precision,
    ph double precision,
    curing_temp_c double precision,
    curing_time_min double precision,
    test_temp_c double precision,
    humidity double precision,
    crosslinker text not null default '',
    substrate text not null default '',
    test_type text not null default 'unknown',
    adhesion_target double precision,
    target_unit text not null default '',
    source_type text not null default 'experiment',
    created_at timestamptz not null default now()
);

create index if not exists idx_adhesion_exp_user
    on public.adhesion_experiments (username, id asc);

-- ===== 安全说明 =====
-- 本应用使用自定义登录（username 随请求发送），RLS 无法据此区分终端用户。
-- 如果部署到公网，建议改用 Supabase Auth，或把数据库访问放到自己的后端 API 中，
-- 并且绝不要在 Streamlit/浏览器端使用 service_role key。
--
-- 如果坚持使用 anon key + 自定义登录，请不要把 RLS 配置成“任何人都能读写全部数据”
-- 后就认为安全；至少应限制 anon 权限，并评估数据泄露风险。
