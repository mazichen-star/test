-- ===== 删除自己的账号（Auth + 业务数据） =====
create or replace function public.delete_my_account()
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
    uname text;
begin
    if auth.uid() is null then
        raise exception 'not authenticated';
    end if;
    uname := public.current_username();
    if uname is null then
        raise exception 'profile not found';
    end if;

    delete from public.user_files where username = uname;
    delete from public.adhesion_literature where username = uname;
    delete from public.adhesion_experiments where username = uname;
    update public.material_library
       set contributor = '已注销用户'
     where contributor = uname;

    delete from public.profiles where id = auth.uid();
    delete from auth.users where id = auth.uid();
end;
$$;

revoke all on function public.delete_my_account() from public;
grant execute on function public.delete_my_account() to authenticated;

