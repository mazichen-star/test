-- ===== 基础表 =====
create table if not exists public.users (
    id bigint generated by default as identity primary key,
    username text not null unique,
    password_hash text not null,
    email text not null,
    created_at timestamptz not null default now()
);

create index if not exists idx_users_email on public.users (email);

create table if not exists public.user_files (
    id bigint generated by default as identity primary key,
    username text not null,
    filename text not null,
    content text not null,              -- PostgREST bytea 十六进制格式：\x...
    uploaded_at timestamptz not null default now(),
    unique (username, filename)
);

create index if not exists idx_user_files_user
    on public.user_files (username, uploaded_at desc);

create table if not exists public.material_library (
    id bigint generated by default as identity primary key,
    formula text not null,
    structure text not null default '',
    properties jsonb not null default '{}'::jsonb,
    source text not null default '',
    reference text not null default '',
    contributor text not null,
    created_at timestamptz not null default now()
);

create index if not exists idx_material_formula
    on public.material_library (formula);

